import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

/**
 * Build from the unchanged vendored originals, with deterministic IDs and ordering.
 * @param {Record<string, string>} icons
 * @param {string} [metadata] Distributed attribution, preserved as escaped XML text.
 */
export function renderIconSprite(icons, metadata = '') {
  const symbols = Object.entries(icons).sort(([a],[b])=>a<b?-1:a>b?1:0).map(([id,svg])=>{
    const match = svg.match(/<svg\b([^>]*)>([\s\S]*?)<\/svg>/);
    const viewBox = match?.[1].match(/viewBox="([^"]+)"/)?.[1];
    if (!match || !viewBox) throw new Error(`Invalid icon: ${id}`);
    const paint=['fill','stroke','stroke-width','stroke-linecap','stroke-linejoin'].map(name=>match[1].match(new RegExp(`\\b${name}="([^"]+)"`))?.[0]??'').filter(Boolean).join(' ');
    const body = match[2].replace(/\bid="([^"]+)"/g,`id="${id}-$1"`).replace(/url\(#([^)]*)\)/g,`url(#${id}-$1)`).replace(/\b((?:xlink:)?href)="#([^"]+)"/g,`$1="#${id}-$2"`);
    return `<symbol id="${id}" viewBox="${viewBox}"${paint?' '+paint:''}>${body}</symbol>`;
  });
  const notice = metadata ? `<metadata>${metadata.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')}</metadata>\n` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg"><!-- Generated by scripts/build-icon-sprites.mjs. Catppuccin license: catppuccin/LICENSE.txt. -->\n${notice}${symbols.join('\n')}\n</svg>\n`;
}

/** @param {'material' | 'catppuccin'} pack */
export async function buildIconSprite(pack) {
  const artworkDir = fileURLToPath(new URL(`../src/lib/components/icons/${pack}/`, import.meta.url));
  const filenames = (await readdir(artworkDir)).filter(name=>name.endsWith('.svg'));
  const icons = Object.fromEntries(await Promise.all(filenames.map(async name=>[path.basename(name,'.svg'),await readFile(path.join(artworkDir,name),'utf8')])));
  const notice = pack === 'catppuccin' ? await readFile(path.join(artworkDir,'LICENSE.txt'),'utf8') : '';
  return renderIconSprite(icons, notice);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for(const pack of /** @type {const} */ (['material','catppuccin'])) {
    const sprite = await buildIconSprite(pack);
    const output = fileURLToPath(new URL(`../src/lib/components/icons/${pack}-sprite.svg`, import.meta.url));
    if (process.argv.includes('--check')) {
      if (await readFile(output,'utf8') !== sprite) throw new Error(`${pack} sprite is stale; run node scripts/build-icon-sprites.mjs`);
    } else await writeFile(output,sprite);
  }
}
